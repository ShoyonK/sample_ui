"""Writes the Station API's machine-checked reference from the protocol package (src/station_protocol).

    uv run python scripts/api/build.py            # writes both files
    uv run python scripts/api/build.py --check    # exits 1 if either is out of date (tests/unit/test_api_docs.py)

docs/station_api.schema.json  JSON Schema (2020-12) of every method's params and result, every event's data and
                              the error object, from the protocol's types (station_protocol.catalog).
docs/STATION_API_REFERENCE.md Per method: parameters, result, requires and examples; then the events, errors and
                              types. Every example is the exact JSON a station sends for the reference fixture.

The schema and the reference's shapes come from station_protocol alone. Only the examples need a station: here,
this repository's fake (requests go through FakeStationServer._handle on a manual clock, so they're
deterministic); in the station's repository, its simulation mode. That part is marked below.

The rules behind the shapes (what each call does, state, activities, timeouts) are in docs/STATION_API.md.
"""

from __future__ import annotations

import itertools
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from pydantic import TypeAdapter  # noqa: E402
from typing_extensions import NotRequired, TypedDict  # noqa: E402

from station_protocol import PROTOCOL_VERSION, jsonrpc  # noqa: E402
from station_protocol.catalog import EVENTS, METHODS, TOPICS  # noqa: E402
from station_protocol.errors import ErrorCode  # noqa: E402
from station_protocol.framing import MAX_FRAME  # noqa: E402
from station_protocol.method import Method  # noqa: E402

SCHEMA = ROOT / "docs" / "station_api.schema.json"
REFERENCE = ROOT / "docs" / "STATION_API_REFERENCE.md"
REF = "#/$defs/{model}"

AREAS = [("sys", "Handshake and station status"), ("dut", "DUT connection"), ("registers", "Registers"),
         ("memory", "Memory"), ("rf", "RF switch and PRS"), ("instruments", "Instruments"),
         ("automation", "Running actions"), ("activity", "Activities"), ("tests", "Test execution"),
         ("advanced", "Python and DUT control")]


# ---- the wire types of each method ------------------------------------------------------------------------------

def params_type(method: Method) -> Any:
    fields = {p.wire: (p.type if p.required else NotRequired[p.type]) for p in method.params}
    return TypedDict(f"P__{method.wire.replace('.', '_')}", fields)  # type: ignore[operator]


def result_type(method: Method) -> Any:
    if method.result is None:
        return TypedDict(f"R__{method.wire.replace('.', '_')}", {})  # type: ignore[operator]   # Empty
    if method.wrap:
        return TypedDict(f"R__{method.wire.replace('.', '_')}", {method.wrap: method.result})  # type: ignore[operator]
    return method.result


ERROR_DEF = {
    "type": "object", "title": "Error",
    "description": "A JSON-RPC error object. `data.reason` is the Station API code; the rest of `data` is its detail.",
    "properties": {"code": {"type": "integer"}, "message": {"type": "string"},
                   "data": {"type": "object", "properties": {"reason": {"enum": [c.value for c in ErrorCode]}},
                            "required": ["reason"]}},
    "required": ["code", "message", "data"],
}


def build_schema() -> Dict[str, Any]:
    inputs: List[Tuple[Tuple[str, str], str, TypeAdapter]] = []
    for m in METHODS:
        inputs.append(((m.wire, "params"), "validation", TypeAdapter(params_type(m))))
        inputs.append(((m.wire, "result"), "validation", TypeAdapter(result_type(m))))
    for event in EVENTS:
        inputs.append(((event.name, "data"), "validation", TypeAdapter(event.data)))
    refs, top = TypeAdapter.json_schemas(inputs, ref_template=REF)
    defs = dict(top.get("$defs", {}))
    defs["Error"] = ERROR_DEF
    methods = {}
    for m in METHODS:
        methods[m.wire] = {"params": _with_defaults(m, refs[((m.wire, "params"), "validation")], defs),
                           "result": refs[((m.wire, "result"), "validation")],
                           "requires": list(m.requires)}
    events = {e.name: {"topic": e.topic or "(the caller)", "data": refs[((e.name, "data"), "validation")]}
              for e in EVENTS}
    return {"$schema": "https://json-schema.org/draft/2020-12/schema", "title": "SiRAT Station API",
            "description": "Generated by scripts/api/build.py from src/station_protocol. Rules: docs/STATION_API.md.",
            "protocol": PROTOCOL_VERSION, "max_frame_bytes": MAX_FRAME, "topics": list(TOPICS),
            "errors": {code.value: jsonrpc.CODES[code] for code in ErrorCode},
            "methods": methods, "events": events, "$defs": dict(sorted(defs.items()))}


def _with_defaults(method: Method, schema: Dict[str, Any], defs: Dict[str, Any]) -> Dict[str, Any]:
    """Params schemas are generated TypedDicts: resolve them inline and add each parameter's default."""
    target = defs.get(schema["$ref"].split("/")[-1]) if "$ref" in schema else schema
    assert target is not None
    body = {k: v for k, v in target.items() if k != "title"}
    for p in method.params:
        if not p.required:
            body["properties"][p.wire] = {**body["properties"][p.wire], "default": p.default}
    body["additionalProperties"] = False   # the station refuses unknown parameters
    return body


def _drop_generated_defs(schema: Dict[str, Any]) -> Dict[str, Any]:
    """Inline the per-method result TypedDicts too, and drop both kinds of generated def."""
    defs = schema["$defs"]
    for entry in schema["methods"].values():
        ref = entry["result"].get("$ref", "")
        name = ref.split("/")[-1]
        if name.startswith("R__"):
            entry["result"] = {k: v for k, v in defs[name].items() if k != "title"}
    schema["$defs"] = {k: v for k, v in defs.items() if not k.startswith(("P__", "R__"))}
    return schema


